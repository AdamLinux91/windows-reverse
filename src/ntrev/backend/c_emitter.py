"""
Custom Verified LLVM IR + Structural Map -> Exact C/C++ Source Replica Emitter.

Transforms Z3-verified LLVM 22 SSA IR, PDB/reconstructed structure definitions,
rerolled loops, strength-reduced divisions, named kernel globals, and preserved
kernel inline-assembly blocks into clean, idiomatic, `-Wall -Werror` compilable
C11/C++ source and header files.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from ntrev.frontend.asm_detector import AsmBlockDetector
from ntrev.models import (
    EquivalenceProof,
    FieldAccessRef,
    FunctionCFG,
    InferredFuncSignature,
    KernelGlobalRef,
    RecoveredDivMod,
    RerolledLoop,
    StructDef,
    StructField,
)
from ntrev.symbols.nt_types import KNOWN_WDK_PROTOTYPES, KPCR_GS_OFFSETS


@dataclass
class IRBasicBlock:
    label: str
    phis: list[tuple[str, int, list[tuple[str, str]]]]  # (lhs, bits, [(val, pred_lbl)])
    stmts: list[str]
    terminator: str


class VerifiedCEmitter:
    """Emits layout-exact C headers and Z3-verified C source replicas."""

    def __init__(
        self,
        structs: dict[str, StructDef] | None = None,
        known_signatures: dict[str, InferredFuncSignature] | None = None,
    ) -> None:
        self.structs: dict[str, StructDef] = structs or {}
        self.known_signatures: dict[str, InferredFuncSignature] = dict(known_signatures or {})
        for fname, (ret_ty, params) in KNOWN_WDK_PROTOTYPES.items():
            if fname not in self.known_signatures:
                self.known_signatures[fname] = InferredFuncSignature(
                    name=fname,
                    return_type=ret_ty,
                    params=list(params),
                    is_void_return=(ret_ty == "void"),
                )
        self._asm_detector = AsmBlockDetector()

    # ------------------------------------------------------------------
    # Header Generation (byte-exact struct padding, unions, globals & prototypes)
    # ------------------------------------------------------------------
    def emit_header(
        self,
        structs: list[StructDef],
        signatures: list[tuple[InferredFuncSignature, bool]],
        globals_list: list[KernelGlobalRef] | None = None,
        c_callable_asm_names: set[str] | None = None,
        header_guard: str = "NTREV_RECONSTRUCTED_TYPES_H",
    ) -> str:
        c_callable_asm = c_callable_asm_names or set()
        ordered_structs = self._expand_and_toposort_structs(structs)
        emitted_struct_names = {s.name for s in ordered_structs}

        lines: list[str] = [
            "/*",
            " * Auto-generated by ntrev — Windows NT Binary-to-Source Replica Header",
            " * Layout-verified structure definitions with exact byte-offset padding.",
            " */",
            f"#ifndef {header_guard}",
            f"#define {header_guard}",
            "",
            "#include <stdint.h>",
            "#include <stddef.h>",
            "#include <stdbool.h>",
            "",
            "typedef int32_t  NTSTATUS;",
            "typedef int32_t  LONG;",
            "typedef uint32_t ULONG;",
            "typedef uint64_t ULONG_PTR;",
            "typedef uint8_t  BOOLEAN;",
            "typedef uint8_t  KIRQL;",
            "typedef void*    PVOID;",
            "",
            "#ifndef STATUS_SUCCESS",
            "#define STATUS_SUCCESS ((NTSTATUS)0x00000000L)",
            "#endif",
            "#ifndef STATUS_BUFFER_TOO_SMALL",
            "#define STATUS_BUFFER_TOO_SMALL ((NTSTATUS)0xC0000023L)",
            "#endif",
            "",
            "#ifndef CONTAINING_RECORD",
            "#define CONTAINING_RECORD(address, type, field) \\",
            "    ((type *)((uint8_t *)(uintptr_t)(address) - offsetof(type, field)))",
            "#endif",
            "",
            "static inline uint64_t __ntrev_readgsqword(uint32_t offset) {",
            "    uint64_t val = 0;",
            "#if defined(__x86_64__) || defined(_M_X64)",
            '    __asm__ __volatile__ ("movq %%gs:(%1), %0" : "=r"(val) : "r"((uint64_t)offset));',
            "#endif",
            "    return val;",
            "}",
            "",
        ]

        # Forward declarations
        for st in ordered_structs:
            kw = "union" if st.is_union else "struct"
            lines.append(f"{kw} {st.name};")
            if st.typedef_name:
                lines.append(f"typedef {kw} {st.name} {st.typedef_name};")
            if st.pointer_typedef:
                lines.append(f"typedef {kw} {st.name}* {st.pointer_typedef};")

        # Forward-declare any pointer-only referenced struct/union tags from prototypes/fields
        extra_tags = self._collect_unemitted_tags(ordered_structs, signatures, emitted_struct_names)
        for kw, tname in sorted(extra_tags):
            lines.append(f"{kw} {tname};")

        if ordered_structs or extra_tags:
            lines.append("")

        defined_fn_names = {sig.name for sig, _ in signatures}
        if "_KTHREAD" in emitted_struct_names and "KeGetCurrentThread" not in defined_fn_names:
            lines.extend(
                [
                    "static inline struct _KTHREAD* KeGetCurrentThread(void) {",
                    "    return (struct _KTHREAD*)(uintptr_t)__ntrev_readgsqword(0x188);",
                    "}",
                    "",
                ]
            )
        if "_KPRCB" in emitted_struct_names and "KeGetCurrentPrcb" not in defined_fn_names:
            lines.extend(
                [
                    "static inline struct _KPRCB* KeGetCurrentPrcb(void) {",
                    "    return (struct _KPRCB*)(uintptr_t)__ntrev_readgsqword(0x20);",
                    "}",
                    "",
                ]
            )

        # Full layout-accurate struct/union definitions
        for st in ordered_structs:
            lines.append(self.format_struct_definition(st, emitted_struct_names=emitted_struct_names))
            lines.append("")

        # Kernel global data symbols referenced via RIP-relative addressing
        if globals_list:
            lines.append("/* Reconstructed Kernel Global Symbols */")
            seen_g: set[str] = set()
            for g in globals_list:
                if g.name in seen_g:
                    continue
                seen_g.add(g.name)
                lines.append(self.format_global_declaration(g, is_extern=True))
            lines.append("")

        # Function prototypes
        lines.append("/* Reconstructed Function Prototypes */")
        for sig, is_raw_asm in signatures:
            if is_raw_asm and sig.name not in c_callable_asm:
                lines.append(f"void {sig.name}(void);")
            else:
                lines.append(f"{sig.format_prototype(include_abi=True)};")

        lines.append("")
        lines.append(f"#endif /* {header_guard} */")
        return "\n".join(lines)

    @staticmethod
    def format_global_declaration(g: KernelGlobalRef, is_extern: bool = True) -> str:
        prefix = "extern " if is_extern else ""
        if g.name == "ObTypeIndexTable":
            if is_extern:
                return "extern struct _OBJECT_TYPE* ObTypeIndexTable[256];"
            return "struct _OBJECT_TYPE* ObTypeIndexTable[256] = {0};"
        const_kw = "const " if g.is_const else ""
        if g.is_array_or_addr and g.size >= 8:
            if is_extern:
                return f"extern {const_kw}uint8_t {g.name}[];"
            if g.initial_bytes:
                hex_items = ", ".join(f"0x{b:02x}" for b in g.initial_bytes)
                arr_len = max(len(g.initial_bytes), 64)
                return f"{const_kw}uint8_t {g.name}[{arr_len}] = {{ {hex_items} }};"
            return f"{const_kw}uint8_t {g.name}[4096] = {{0}};"
        if is_extern:
            return f"{prefix}{const_kw}{g.c_type} {g.name};"
        init_val = f"0x{g.initial_value:x}ULL" if g.initial_value is not None else "0"
        return f"{const_kw}{g.c_type} {g.name} = ({g.c_type})({init_val});"

    def _expand_and_toposort_structs(self, initial_structs: list[StructDef]) -> list[StructDef]:
        by_name: dict[str, StructDef] = {st.name: st for st in initial_structs}

        # Pull in small (< 256B) embedded by-value structs present in `self.structs`
        queue = list(initial_structs)
        while queue:
            cur = queue.pop(0)
            for fld in cur.fields:
                if fld.is_pointer:
                    continue
                m = re.match(r"^(struct|union)\s+([A-Za-z0-9_]+)$", fld.c_type.strip())
                if m:
                    dep_name = m.group(2)
                    if dep_name not in by_name and dep_name in self.structs:
                        dep_st = self.structs[dep_name]
                        if dep_st.size <= 2048 or dep_name in ("_KTHREAD", "_OBJECT_HEADER"):
                            by_name[dep_name] = dep_st
                            queue.append(dep_st)

        # Topological sort by embedded by-value struct dependencies
        visited: set[str] = set()
        visiting: set[str] = set()
        ordered: list[StructDef] = []

        def dfs(sname: str) -> None:
            if sname in visited or sname not in by_name:
                return
            if sname in visiting:
                return
            visiting.add(sname)
            st = by_name[sname]
            for fld in st.fields:
                if not fld.is_pointer:
                    m = re.match(r"^(struct|union)\s+([A-Za-z0-9_]+)$", fld.c_type.strip())
                    if m and m.group(2) in by_name and m.group(2) != sname:
                        dfs(m.group(2))
            visiting.remove(sname)
            visited.add(sname)
            ordered.append(st)

        for st in initial_structs:
            dfs(st.name)
        for sname in list(by_name.keys()):
            dfs(sname)
        return ordered

    def _collect_unemitted_tags(
        self,
        ordered_structs: list[StructDef],
        signatures: list[tuple[InferredFuncSignature, bool]],
        emitted_names: set[str],
    ) -> set[tuple[str, str]]:
        tags: set[tuple[str, str]] = set()
        pat = re.compile(r"\b(struct|union)\s+([A-Za-z_][A-Za-z0-9_]*)")
        for st in ordered_structs:
            for fld in st.fields:
                for m in pat.finditer(fld.c_type):
                    if m.group(2) not in emitted_names:
                        tags.add((m.group(1), m.group(2)))
        for sig, _ in signatures:
            for m in pat.finditer(sig.return_type):
                if m.group(2) not in emitted_names:
                    tags.add((m.group(1), m.group(2)))
            for _, pty in sig.params:
                for m in pat.finditer(pty):
                    if m.group(2) not in emitted_names:
                        tags.add((m.group(1), m.group(2)))
        return tags

    @classmethod
    def format_struct_definition(
        cls,
        st: StructDef,
        emitted_struct_names: set[str] | None = None,
    ) -> str:
        kw = "union" if st.is_union else "struct"
        lines = [f"/* Source: {st.source} | Size: 0x{st.size:x} ({st.size} bytes) */"]
        if st.is_union:
            lines.append(f"union {st.name} {{")
            used_names: set[str] = set()
            for fld in st.fields:
                if fld.bit_size is not None:
                    continue
                fname = cls._unique_field_name(fld.name, used_names)
                lines.append("    " + cls._format_single_field(fld, fname, emitted_struct_names))
            if st.size > 0:
                lines.append(f"    uint8_t _raw_bytes[0x{st.size:x}];")
            lines.append("};")
            return "\n".join(lines)

        # Partition non-bitfield members into non-overlapping sequential lanes.
        # Lane 0 holds primary non-overlapping members; overlapping union-like PDB members
        # go into parallel lanes wrapped inside a C11 anonymous `union { ... }` when >1 lane exists!
        non_bf = [
            f
            for f in sorted(st.fields, key=lambda x: (x.offset, -x.size, x.name))
            if f.bit_size is None and f.offset < max(st.size, 1)
        ]

        lanes: list[list[StructField]] = []
        used_names = set()
        renamed_fields: list[tuple[StructField, str]] = []
        for fld in non_bf:
            fname = cls._unique_field_name(fld.name, used_names)
            renamed_fields.append((fld, fname))

        lane_tuples: list[list[tuple[StructField, str]]] = []
        lane_ends: list[int] = []
        for fld, fname in renamed_fields:
            f_end = fld.offset + max(fld.size, 1)
            if st.size > 0 and f_end > st.size:
                continue
            placed = False
            for l_idx, cur_end in enumerate(lane_ends):
                if fld.offset >= cur_end:
                    lane_tuples[l_idx].append((fld, fname))
                    lane_ends[l_idx] = f_end
                    placed = True
                    break
            if not placed and len(lane_tuples) < 12:
                lane_tuples.append([(fld, fname)])
                lane_ends.append(f_end)

        lines.append(f"struct __attribute__((packed)) {st.name} {{")
        if len(lane_tuples) <= 1:
            lane0 = lane_tuples[0] if lane_tuples else []
            for ln in cls._render_packed_lane(lane0, st.size, "    ", emitted_struct_names, 0):
                lines.append(ln)
        else:
            lines.append("    union {")
            for l_idx, lt in enumerate(lane_tuples):
                lines.append("        struct __attribute__((packed)) {")
                for ln in cls._render_packed_lane(
                    lt, st.size, "            ", emitted_struct_names, l_idx
                ):
                    lines.append(ln)
                lines.append("        };")
            lines.append("    };")
        lines.append("};")
        return "\n".join(lines)

    @classmethod
    def _render_packed_lane(
        cls,
        lane: list[tuple[StructField, str]],
        total_size: int,
        indent: str,
        emitted_struct_names: set[str] | None,
        lane_id: int,
    ) -> list[str]:
        out: list[str] = []
        cur_off = 0
        pad_idx = 0
        for fld, fname in lane:
            if fld.offset > cur_off:
                gap = fld.offset - cur_off
                out.append(f"{indent}uint8_t _pad_l{lane_id}_{pad_idx}_0x{cur_off:x}[0x{gap:x}];")
                pad_idx += 1
                cur_off = fld.offset
            out.append(indent + cls._format_single_field(fld, fname, emitted_struct_names))
            cur_off = fld.offset + max(fld.size, 1)
        if total_size > cur_off:
            tail = total_size - cur_off
            out.append(f"{indent}uint8_t _pad_l{lane_id}_tail_0x{cur_off:x}[0x{tail:x}];")
        return out

    @staticmethod
    def _unique_field_name(raw_name: str, used: set[str]) -> str:
        clean = re.sub(r"[^A-Za-z0-9_]", "_", raw_name or "field")
        if not clean or clean[0].isdigit() or clean in ("__unnamed", "register", "inline"):
            clean = f"_f_{clean}"
        cand = clean
        idx = 2
        while cand in used:
            cand = f"{clean}_{idx}"
            idx += 1
        used.add(cand)
        return cand

    @staticmethod
    def _format_single_field(
        fld: StructField,
        fname: str,
        emitted_struct_names: set[str] | None,
    ) -> str:
        c_ty = fld.c_type.strip()
        if not fld.is_pointer and emitted_struct_names is not None:
            m = re.match(r"^(struct|union)\s+([A-Za-z0-9_]+)$", c_ty)
            if m and m.group(2) not in emitted_struct_names:
                total_bytes = max(fld.size, 1)
                return f"uint8_t {fname}[0x{total_bytes:x}]; /* {c_ty} +0x{fld.offset:x} */"

        if fld.array_len is not None and fld.array_len > 0:
            return f"{c_ty} {fname}[{fld.array_len}]; /* +0x{fld.offset:x} */"
        return f"{c_ty} {fname}; /* +0x{fld.offset:x} */"

    # ------------------------------------------------------------------
    # Function C Source Generation
    # ------------------------------------------------------------------
    def emit_function(
        self,
        cfg: FunctionCFG,
        signature: InferredFuncSignature,
        optimized_llvm_ir: str,
        field_accesses: list[FieldAccessRef],
        rerolled_loops: list[RerolledLoop],
        recovered_divs: list[RecoveredDivMod],
        proof: EquivalenceProof,
    ) -> str:
        # 1. Whole-function non-C NT kernel assembly -> preserve verbatim with ABI prototype
        if cfg.asm_classification.is_raw_asm:
            return self._asm_detector.format_raw_asm_function(cfg, signature=signature)

        banner = self._format_proof_banner(cfg, proof, rerolled_loops, recovered_divs)
        proto = signature.format_prototype(include_abi=True)

        # 2. Whole-function rerolled loop (5-way multi-branch dispatch, 16x page loop, or linear unroll)
        for rloop in rerolled_loops:
            if rloop.replaces_entire_function:
                body_lines = []
                for ln in rloop.c_loop_code.splitlines():
                    if ln.startswith("return ") and not signature.is_void_return:
                        expr = ln[len("return ") : -1]
                        ret_cast = self._cast_return_expr(expr, signature.return_type)
                        body_lines.append(f"    return {ret_cast};")
                    else:
                        body_lines.append(f"    {ln}")
                return f"{banner}\n{proto} {{\n" + "\n".join(body_lines) + "\n}"

        # 3. Single-block pure magic-division/modulo function verified by Z3
        if (
            len(recovered_divs) == 1
            and len(cfg.blocks) == 1
            and not signature.is_void_return
            and not any(ins.mnemonic == "call" for ins in cfg.all_instructions())
        ):
            rdiv = recovered_divs[0]
            tag = "mod" if rdiv.is_modulo else "div"
            if f"magic_{tag}_equivalence:{tag}_{rdiv.divisor}" in proof.verified_stages:
                ret_cast = self._cast_return_expr(rdiv.c_expr, signature.return_type)
                return f"{banner}\n{proto} {{\n    return {ret_cast};\n}}"

        # 4. General SSA LLVM IR -> Structured C Translator with PDB Struct Field Resolution
        body = self._translate_llvm_ir_to_c(
            cfg=cfg,
            optimized_llvm_ir=optimized_llvm_ir,
            signature=signature,
            field_accesses=field_accesses,
            rerolled_loops=rerolled_loops,
            recovered_divs=recovered_divs,
        )
        return f"{banner}\n{proto} {{\n{body}\n}}"

    @staticmethod
    def _cast_return_expr(expr: str, return_type: str) -> str:
        rt = return_type.strip()
        if rt.endswith("*") or rt in ("PVOID", "HANDLE"):
            return f"({rt})(uintptr_t)({expr})"
        return f"({rt})({expr})"

    def _format_proof_banner(
        self,
        cfg: FunctionCFG,
        proof: EquivalenceProof,
        rerolled_loops: list[RerolledLoop],
        recovered_divs: list[RecoveredDivMod],
    ) -> str:
        lines = [
            "/*",
            f" * Function : {cfg.name} @ 0x{cfg.address:x} ({cfg.size} bytes)",
            f" * Z3 Proof : {proof.status} ({proof.solve_time_ms:.2f} ms, {proof.num_assertions} SMT assertions)",
        ]
        if proof.verified_stages:
            lines.append(f" * Verified : {', '.join(proof.verified_stages)}")
        for rl in rerolled_loops:
            lines.append(f" * De-Opt   : {rl.description}")
        for rd in recovered_divs:
            op_s = "%" if rd.is_modulo else "/"
            lines.append(
                f" * De-Opt   : Strength-reduced magic 0x{rd.magic_constant:x} -> '{op_s} {rd.divisor}'"
            )
        lines.append(" */")
        return "\n".join(lines)

    # ------------------------------------------------------------------
    # LLVM 22 SSA IR -> Clean Structured C11 Translator
    # ------------------------------------------------------------------
    def _translate_llvm_ir_to_c(
        self,
        cfg: FunctionCFG,
        optimized_llvm_ir: str,
        signature: InferredFuncSignature,
        field_accesses: list[FieldAccessRef],
        rerolled_loops: list[RerolledLoop],
        recovered_divs: list[RecoveredDivMod],
    ) -> str:
        ir_blocks, ir_args = self._parse_ir_blocks(optimized_llvm_ir)
        if not ir_blocks:
            return "    return;" if signature.is_void_return else "    return 0;"

        val_exprs: dict[str, str] = {}
        ptr_struct_types: dict[str, tuple[str, str]] = {}

        for idx, ir_arg in enumerate(ir_args):
            if idx < len(signature.params):
                pname, ptype = signature.params[idx]
                cast_u64 = f"((uint64_t)(uintptr_t){pname})" if ("*" in ptype or ptype == "PVOID") else f"((uint64_t){pname})"
                val_exprs[ir_arg] = cast_u64
                sname = self._pointee_struct_name(ptype)
                if sname and sname in self.structs:
                    ptr_struct_types[ir_arg] = (sname, pname)
                elif ptype.strip() in ("void*", "PVOID") and cfg.name.startswith("Ob"):
                    ptr_struct_types[ir_arg] = ("__VOID_OB_BODY__", pname)
            else:
                val_exprs[ir_arg] = "0ULL"

        use_counts = self._count_ssa_uses(ir_blocks)

        decl_lines: list[str] = []
        phi_vars: dict[str, str] = {}
        for blk in ir_blocks:
            for lhs, bits, _incoming in blk.phis:
                c_var = self._sanitize_ident(lhs)
                phi_vars[lhs] = c_var
                c_ty = self._bits_to_uint_c(bits)
                decl_lines.append(f"    {c_ty} __attribute__((unused)) {c_var} = 0;")
                val_exprs[lhs] = c_var

        phi_edge_copies: dict[tuple[str, str], list[str]] = {}
        for blk in ir_blocks:
            for lhs, bits, incoming in blk.phis:
                for val_tok, pred_lbl in incoming:
                    phi_edge_copies.setdefault((pred_lbl, blk.label), []).append(
                        f"{phi_vars[lhs]} = ({self._bits_to_uint_c(bits)})({self._tok_Placeholder(val_tok)});"
                    )

        rendered_blocks: dict[str, list[str]] = {}
        block_map = {b.label: b for b in ir_blocks}

        for blk in ir_blocks:
            b_stmts: list[str] = []
            for stmt in blk.stmts:
                emitted = self._emit_ir_stmt(
                    stmt=stmt,
                    val_exprs=val_exprs,
                    ptr_struct_types=ptr_struct_types,
                    use_counts=use_counts,
                    decl_lines=decl_lines,
                    func_name=signature.name,
                )
                if emitted:
                    b_stmts.append(emitted)
            rendered_blocks[blk.label] = b_stmts

        def resolve_placeholders(text: str) -> str:
            return re.sub(
                r"__SSA_TOK\(([^)]+)\)__",
                lambda m: self._resolve_c_tok(m.group(1), val_exprs),
                text,
            )

        if len(ir_blocks) == 1:
            b0 = ir_blocks[0]
            out_lines = list(decl_lines)
            for s in rendered_blocks[b0.label]:
                out_lines.append(f"    {resolve_placeholders(s)}")
            for tl in self._emit_terminator(
                b0, None, signature, val_exprs, phi_edge_copies, resolve_placeholders
            ):
                out_lines.append(f"    {tl}")
            return "\n".join(out_lines)

        structured = self._try_structure_if_diamond(
            ir_blocks,
            block_map,
            rendered_blocks,
            signature,
            val_exprs,
            phi_edge_copies,
            decl_lines,
            resolve_placeholders,
        )
        if structured is not None:
            return structured

        loop_structured = self._try_structure_natural_loop(
            ir_blocks,
            rendered_blocks,
            signature,
            val_exprs,
            phi_edge_copies,
            decl_lines,
            resolve_placeholders,
        )
        if loop_structured is not None:
            return loop_structured

        per_block_lines: list[tuple[str, list[str]]] = []
        used_c_labels: set[str] = set()
        for idx, blk in enumerate(ir_blocks):
            next_lbl = ir_blocks[idx + 1].label if idx + 1 < len(ir_blocks) else None
            blines: list[str] = []
            for s in rendered_blocks[blk.label]:
                blines.append(f"    {resolve_placeholders(s)}")
            for tl in self._emit_terminator(
                blk, next_lbl, signature, val_exprs, phi_edge_copies, resolve_placeholders
            ):
                blines.append(f"    {tl}")
                for m_go in re.finditer(r"\bgoto\s+(L_[A-Za-z0-9_]+)\s*;", tl):
                    used_c_labels.add(m_go.group(1))
            per_block_lines.append((self._c_label(blk.label), blines))

        out_lines = list(decl_lines)
        for c_lbl, blines in per_block_lines:
            if c_lbl in used_c_labels:
                out_lines.append(f"{c_lbl}:")
            out_lines.extend(blines)

        return "\n".join(out_lines)

    # ------------------------------------------------------------------
    # Control-Flow Structuring Patterns (If/Else & Natural Loops)
    # ------------------------------------------------------------------
    def _try_structure_if_diamond(
        self,
        ir_blocks: list[IRBasicBlock],
        block_map: dict[str, IRBasicBlock],
        rendered_blocks: dict[str, list[str]],
        signature: InferredFuncSignature,
        val_exprs: dict[str, str],
        phi_edge_copies: dict[tuple[str, str], list[str]],
        decl_lines: list[str],
        resolve_placeholders,
    ) -> str | None:
        if len(ir_blocks) not in (3, 4):
            return None
        entry = ir_blocks[0]
        m_cbr = re.match(
            r"br\s+i1\s+([^,]+),\s*label\s+%([^\s,]+),\s*label\s+%([^\s,]+)",
            entry.terminator,
        )
        if not m_cbr:
            return None
        cond_expr = self._resolve_c_tok(m_cbr.group(1).strip(), val_exprs)
        t_lbl = m_cbr.group(2).strip('"')
        f_lbl = m_cbr.group(3).strip('"')
        if t_lbl not in block_map or f_lbl not in block_map or t_lbl == entry.label or f_lbl == entry.label:
            return None

        if len(ir_blocks) == 3:
            b_t = block_map[t_lbl]
            b_f = block_map[f_lbl]
            if b_t.terminator.startswith("ret ") and b_f.terminator.startswith("ret "):
                if (entry.label, t_lbl) in phi_edge_copies or (entry.label, f_lbl) in phi_edge_copies:
                    return None
                lines = list(decl_lines)
                for s in rendered_blocks[entry.label]:
                    lines.append(f"    {resolve_placeholders(s)}")
                lines.append(f"    if ({cond_expr}) {{")
                for s in rendered_blocks[t_lbl]:
                    lines.append(f"        {resolve_placeholders(s)}")
                for tl in self._emit_terminator(b_t, None, signature, val_exprs, phi_edge_copies, resolve_placeholders):
                    lines.append(f"        {tl}")
                lines.append("    }")
                for s in rendered_blocks[f_lbl]:
                    lines.append(f"    {resolve_placeholders(s)}")
                for tl in self._emit_terminator(b_f, None, signature, val_exprs, phi_edge_copies, resolve_placeholders):
                    lines.append(f"    {tl}")
                return "\n".join(lines)

            if b_t.terminator in (f"br label %{f_lbl}", f'br label %"{f_lbl}"'):
                lines = list(decl_lines)
                for s in rendered_blocks[entry.label]:
                    lines.append(f"    {resolve_placeholders(s)}")
                lines.append(f"    if ({cond_expr}) {{")
                for s in rendered_blocks[t_lbl]:
                    lines.append(f"        {resolve_placeholders(s)}")
                for cp in phi_edge_copies.get((t_lbl, f_lbl), []):
                    lines.append(f"        {resolve_placeholders(cp)}")
                lines.append("    }")
                if (entry.label, f_lbl) in phi_edge_copies:
                    lines.append("    else {")
                    for cp in phi_edge_copies[(entry.label, f_lbl)]:
                        lines.append(f"        {resolve_placeholders(cp)}")
                    lines.append("    }")
                for s in rendered_blocks[f_lbl]:
                    lines.append(f"    {resolve_placeholders(s)}")
                for tl in self._emit_terminator(b_f, None, signature, val_exprs, phi_edge_copies, resolve_placeholders):
                    lines.append(f"    {tl}")
                return "\n".join(lines)

            if b_f.terminator in (f"br label %{t_lbl}", f'br label %"{t_lbl}"'):
                lines = list(decl_lines)
                for s in rendered_blocks[entry.label]:
                    lines.append(f"    {resolve_placeholders(s)}")
                lines.append(f"    if ({cond_expr}) {{")
                for cp in phi_edge_copies.get((entry.label, t_lbl), []):
                    lines.append(f"        {resolve_placeholders(cp)}")
                lines.append("    } else {")
                for s in rendered_blocks[f_lbl]:
                    lines.append(f"        {resolve_placeholders(s)}")
                for cp in phi_edge_copies.get((f_lbl, t_lbl), []):
                    lines.append(f"        {resolve_placeholders(cp)}")
                lines.append("    }")
                for s in rendered_blocks[t_lbl]:
                    lines.append(f"    {resolve_placeholders(s)}")
                for tl in self._emit_terminator(b_t, None, signature, val_exprs, phi_edge_copies, resolve_placeholders):
                    lines.append(f"    {tl}")
                return "\n".join(lines)

        if len(ir_blocks) == 4:
            b_t = block_map[t_lbl]
            b_f = block_map[f_lbl]
            rem = [b for b in ir_blocks[1:] if b.label not in (t_lbl, f_lbl)]
            if len(rem) == 1:
                merge_b = rem[0]
                m_lbl = merge_b.label
                if (
                    b_t.terminator in (f"br label %{m_lbl}", f'br label %"{m_lbl}"')
                    and b_f.terminator in (f"br label %{m_lbl}", f'br label %"{m_lbl}"')
                    and merge_b.terminator.startswith("ret ")
                ):
                    lines = list(decl_lines)
                    for s in rendered_blocks[entry.label]:
                        lines.append(f"    {resolve_placeholders(s)}")
                    lines.append(f"    if ({cond_expr}) {{")
                    for s in rendered_blocks[t_lbl]:
                        lines.append(f"        {resolve_placeholders(s)}")
                    for cp in phi_edge_copies.get((t_lbl, m_lbl), []):
                        lines.append(f"        {resolve_placeholders(cp)}")
                    lines.append("    } else {")
                    for s in rendered_blocks[f_lbl]:
                        lines.append(f"        {resolve_placeholders(s)}")
                    for cp in phi_edge_copies.get((f_lbl, m_lbl), []):
                        lines.append(f"        {resolve_placeholders(cp)}")
                    lines.append("    }")
                    for s in rendered_blocks[m_lbl]:
                        lines.append(f"    {resolve_placeholders(s)}")
                    for tl in self._emit_terminator(merge_b, None, signature, val_exprs, phi_edge_copies, resolve_placeholders):
                        lines.append(f"    {tl}")
                    return "\n".join(lines)

        return None

    def _try_structure_natural_loop(
        self,
        ir_blocks: list[IRBasicBlock],
        rendered_blocks: dict[str, list[str]],
        signature: InferredFuncSignature,
        val_exprs: dict[str, str],
        phi_edge_copies: dict[tuple[str, str], list[str]],
        decl_lines: list[str],
        resolve_placeholders,
    ) -> str | None:
        if len(ir_blocks) != 3:
            return None
        pre, loop_bb, exit_bb = ir_blocks[0], ir_blocks[1], ir_blocks[2]
        if pre.terminator.strip('"') not in (f"br label %{loop_bb.label}", f'br label %"{loop_bb.label}'):
            if not re.match(rf'br\s+label\s+%"{re.escape(loop_bb.label)}"?$', pre.terminator):
                return None

        m_cbr = re.match(
            r"br\s+i1\s+([^,]+),\s*label\s+%([^\s,]+),\s*label\s+%([^\s,]+)",
            loop_bb.terminator,
        )
        if not m_cbr or not exit_bb.terminator.startswith("ret "):
            return None

        cond_expr = self._resolve_c_tok(m_cbr.group(1).strip(), val_exprs)
        t_lbl = m_cbr.group(2).strip('"')
        f_lbl = m_cbr.group(3).strip('"')

        if t_lbl == loop_bb.label and f_lbl == exit_bb.label:
            keep_going = cond_expr
        elif f_lbl == loop_bb.label and t_lbl == exit_bb.label:
            keep_going = f"!({cond_expr})"
        else:
            return None

        lines = list(decl_lines)
        for s in rendered_blocks[pre.label]:
            lines.append(f"    {resolve_placeholders(s)}")
        for cp in phi_edge_copies.get((pre.label, loop_bb.label), []):
            lines.append(f"    {resolve_placeholders(cp)}")

        lines.append("    while (1) {")
        for s in rendered_blocks[loop_bb.label]:
            lines.append(f"        {resolve_placeholders(s)}")
        lines.append(f"        if (!({keep_going})) {{")
        for cp in phi_edge_copies.get((loop_bb.label, exit_bb.label), []):
            lines.append(f"            {resolve_placeholders(cp)}")
        lines.append("            break;")
        lines.append("        }")
        back_copies = phi_edge_copies.get((loop_bb.label, loop_bb.label), [])
        for idx_c, cp in enumerate(back_copies):
            rhs = resolve_placeholders(cp.split("=", 1)[1].strip().rstrip(";"))
            lines.append(f"        uint64_t _next_phi_{idx_c} = {rhs};")
        for idx_c, cp in enumerate(back_copies):
            lhs_var = cp.split("=", 1)[0].strip()
            lines.append(f"        {lhs_var} = _next_phi_{idx_c};")
        lines.append("    }")

        for s in rendered_blocks[exit_bb.label]:
            lines.append(f"    {resolve_placeholders(s)}")
        for tl in self._emit_terminator(exit_bb, None, signature, val_exprs, phi_edge_copies, resolve_placeholders):
            lines.append(f"    {tl}")
        return "\n".join(lines)

    # ------------------------------------------------------------------
    # Statement & Expression Lowering with PDB Struct Field Resolution
    # ------------------------------------------------------------------
    def _emit_ir_stmt(
        self,
        stmt: str,
        val_exprs: dict[str, str],
        ptr_struct_types: dict[str, tuple[str, str]],
        use_counts: dict[str, int],
        decl_lines: list[str],
        func_name: str = "",
    ) -> str | None:
        m_asm = re.match(r'(?:tail\s+)?call\s+void\s+asm(?:\s+sideeffect)?\s+"([^"]+)"', stmt)
        if m_asm:
            asm_body = m_asm.group(1)
            return (
                f'__asm__ __volatile__ (".intel_syntax noprefix; {asm_body}; .att_syntax prefix" '
                ': : : "memory", "cc");'
            )

        m_st = re.match(
            r"store\s+i(\d+)\s+([^,]+),\s*(?:ptr|i\d+\*)\s+(inttoptr\s*\([^)]+\)|[^\s,]+)",
            stmt,
        )
        if m_st:
            bits = int(m_st.group(1))
            val_c = self._resolve_c_tok(m_st.group(2), val_exprs)
            ptr_tok = self._norm_tok(m_st.group(3))
            deref_c, field_ty = self._format_mem_lvalue(ptr_tok, bits, val_exprs, ptr_struct_types)
            if "*" in field_ty or field_ty == "PVOID":
                return f"{deref_c} = ({field_ty})(uintptr_t)({val_c});"
            return f"{deref_c} = ({field_ty})({val_c});"

        if "=" not in stmt:
            return None

        lhs_raw, rhs_raw = stmt.split("=", 1)
        lhs = self._norm_tok(lhs_raw)
        rhs = re.sub(
            r"\b(nuw|nsw|exact|disjoint|nneg|inbounds|samesign|tail|notail)\b\s*",
            "",
            rhs_raw.strip(),
        ).strip()

        # Stack alloca `[N x i8]`
        m_alloca = re.match(r"alloca\s+\[(\d+)\s*x\s*i8\]", rhs)
        if m_alloca:
            buf_sz = int(m_alloca.group(1))
            c_var = self._sanitize_ident(lhs)
            decl_lines.append(f"    uint8_t __attribute__((aligned(16))) {c_var}[{buf_sz}];")
            val_exprs[lhs] = f"((uint64_t)(uintptr_t){c_var})"
            return None

        # inttoptr / ptrtoint
        m_itp = re.match(r"inttoptr\s+i\d+\s+([^\s]+)\s+to\s+", rhs)
        if m_itp:
            src_tok = self._norm_tok(m_itp.group(1))
            val_exprs[lhs] = self._resolve_c_tok(src_tok, val_exprs)
            if src_tok in ptr_struct_types:
                ptr_struct_types[lhs] = ptr_struct_types[src_tok]
            return None

        m_pti = re.match(r"ptrtoint\s+(?:ptr|[^\s]+)\s+([^\s]+)\s+to\s+i(\d+)", rhs)
        if m_pti:
            src_tok = self._norm_tok(m_pti.group(1))
            val_exprs[lhs] = self._resolve_c_tok(src_tok, val_exprs)
            return None

        # Array GEP: `getelementptr [4096 x i8], ptr %stack_frame, i64 0, i64 %idx`
        m_gep_arr = re.match(
            r"getelementptr\s+\[\d+\s*x\s*i8\],\s*ptr\s+([^,]+),\s*i\d+\s+0,\s*i\d+\s+([^\s,]+)",
            rhs,
        )
        if m_gep_arr:
            base_c = self._resolve_c_tok(m_gep_arr.group(1), val_exprs)
            idx_c = self._resolve_c_tok(m_gep_arr.group(2), val_exprs)
            val_exprs[lhs] = f"({base_c} + (uint64_t)({idx_c}))"
            return None

        # GEP: `getelementptr iN, ptr %base, i64 %idx`
        m_gep = re.match(r"getelementptr\s+i(\d+),\s*ptr\s+([^,]+),\s*i\d+\s+([^\s,]+)", rhs)
        if m_gep:
            elem_bytes = int(m_gep.group(1)) // 8
            base_tok = self._norm_tok(m_gep.group(2))
            idx_raw = m_gep.group(3).strip()
            base_c = self._resolve_c_tok(base_tok, val_exprs)
            try:
                byte_disp = int(idx_raw, 0) * elem_bytes
                if base_tok in ptr_struct_types:
                    sname, pexpr = ptr_struct_types[base_tok]
                    self._record_offset_ptr(lhs, sname, pexpr, byte_disp, ptr_struct_types)
                val_exprs[lhs] = (
                    f"({base_c} + {byte_disp}ULL)"
                    if byte_disp >= 0
                    else f"({base_c} - {-byte_disp}ULL)"
                )
            except ValueError:
                idx_c = self._resolve_c_tok(idx_raw, val_exprs)
                scale_s = f" * {elem_bytes}ULL" if elem_bytes > 1 else ""
                val_exprs[lhs] = f"({base_c} + (uint64_t)({idx_c}){scale_s})"
            return None

        # Kernel global address helper: `@__nt_sym_addr_<Sym>()`
        m_sym = re.match(r"call\s+i64\s+@__nt_sym_addr_([A-Za-z0-9_$.]+)\(\s*\)", rhs)
        if m_sym:
            sname = m_sym.group(1)
            val_exprs[lhs] = f"((uint64_t)(uintptr_t)&{sname})"
            return None

        # KPCR gs: helper `@__nt_read_gs_iN(i64 disp)`
        m_gs = re.match(r"call\s+i(\d+)\s+@__nt_read_gs_i\d+\(\s*i64\s+([^)]+)\)", rhs)
        if m_gs:
            disp_str = m_gs.group(2).strip()
            c_var = self._sanitize_ident(lhs)
            try:
                disp = int(disp_str, 0)
                kpcr = KPCR_GS_OFFSETS.get(disp)
                if kpcr and not (func_name and kpcr[0].startswith(func_name + "(")):
                    gs_expr, _gs_ty, pointee = kpcr
                    if pointee and pointee in self.structs:
                        kw = "union" if self.structs[pointee].is_union else "struct"
                        val_exprs[lhs] = f"((uint64_t)(uintptr_t){c_var})"
                        ptr_struct_types[lhs] = (pointee, c_var)
                        return f"{kw} {pointee}* __attribute__((unused)) {c_var} = {gs_expr};"
                    val_exprs[lhs] = f"((uint64_t)(uintptr_t)({gs_expr}))"
                    return None
                val_exprs[lhs] = f"__ntrev_readgsqword(0x{disp:x})"
                return None
            except ValueError:
                val_exprs[lhs] = (
                    f"__ntrev_readgsqword((uint32_t)({self._resolve_c_tok(disp_str, val_exprs)}))"
                )
                return None

        # Memory load: `load iN, ptr %p`
        m_ld = re.match(
            r"load\s+i(\d+),\s*(?:ptr|i\d+\*)\s+(inttoptr\s*\([^)]+\)|[^\s,]+)",
            rhs,
        )
        if m_ld:
            bits = int(m_ld.group(1))
            ptr_tok = self._norm_tok(m_ld.group(2))
            deref_c, field_ty = self._format_mem_lvalue(ptr_tok, bits, val_exprs, ptr_struct_types)
            c_var = self._sanitize_ident(lhs)
            pointee = self._pointee_struct_name(field_ty)
            if pointee and pointee in self.structs:
                kw = "union" if self.structs[pointee].is_union else "struct"
                val_exprs[lhs] = f"((uint64_t)(uintptr_t){c_var})"
                ptr_struct_types[lhs] = (pointee, c_var)
                return f"{kw} {pointee}* __attribute__((unused)) {c_var} = ({kw} {pointee}*)(uintptr_t)({deref_c});"
            c_uint = self._bits_to_uint_c(bits)
            val_exprs[lhs] = c_var
            if "*" in field_ty or field_ty == "PVOID":
                return f"{c_uint} __attribute__((unused)) {c_var} = ({c_uint})(uintptr_t)({deref_c});"
            return f"{c_uint} __attribute__((unused)) {c_var} = ({c_uint})({deref_c});"

        # Direct external function call: `call i64 @callee(...)`
        m_call = re.match(r"call\s+i(\d+)\s+@([A-Za-z0-9_.$]+)\(([^)]*)\)", rhs)
        if m_call and not m_call.group(2).startswith("llvm."):
            bits = int(m_call.group(1))
            callee = m_call.group(2)
            raw_args = [a.strip() for a in m_call.group(3).split(",") if a.strip()]
            c_args: list[str] = []
            for a in raw_args:
                parts = a.split()
                c_args.append(self._resolve_c_tok(parts[-1], val_exprs))

            csig = self.known_signatures.get(callee)
            if csig is not None:
                typed_args: list[str] = []
                for idx_a, ca in enumerate(c_args[: len(csig.params)]):
                    pty = csig.params[idx_a][1]
                    if "*" in pty or pty == "PVOID":
                        typed_args.append(f"({pty})(uintptr_t)({ca})")
                    else:
                        typed_args.append(f"({pty})({ca})")
                if csig.is_void_return:
                    val_exprs[lhs] = "0ULL"
                    return f"{callee}({', '.join(typed_args)});"
                c_var = self._sanitize_ident(lhs)
                c_ty = self._bits_to_uint_c(bits)
                val_exprs[lhs] = c_var
                if "*" in csig.return_type or csig.return_type == "PVOID":
                    return f"{c_ty} __attribute__((unused)) {c_var} = ({c_ty})(uintptr_t){callee}({', '.join(typed_args)});"
                return f"{c_ty} __attribute__((unused)) {c_var} = ({c_ty}){callee}({', '.join(typed_args)});"

            c_var = self._sanitize_ident(lhs)
            c_ty = self._bits_to_uint_c(bits)
            val_exprs[lhs] = c_var
            return f"{c_ty} __attribute__((unused)) {c_var} = {callee}({', '.join(c_args)});"

        # Pure expressions
        expr, bits = self._eval_pure_rhs(lhs, rhs, val_exprs, ptr_struct_types)
        if expr is None:
            val_exprs[lhs] = "0ULL"
            return None

        if use_counts.get(lhs, 0) <= 1 or bits == 1 or bits > 64:
            val_exprs[lhs] = expr
            return None

        c_var = self._sanitize_ident(lhs)
        c_ty = self._bits_to_uint_c(bits)
        val_exprs[lhs] = c_var
        return f"{c_ty} __attribute__((unused)) {c_var} = ({c_ty})({expr});"

    def _eval_pure_rhs(
        self,
        lhs: str,
        rhs: str,
        val_exprs: dict[str, str],
        ptr_struct_types: dict[str, tuple[str, str]],
    ) -> tuple[str | None, int]:
        # LLVM `@llvm.abs.iN(iN %x, i1 %is_int_min_poison)`
        m_abs = re.match(
            r"(?:tail\s+)?call\s+i(\d+)\s+@llvm\.abs\.[a-z0-9.]+\(\s*i\d+\s+([^,]+),\s*i1\s+[^)]+\)",
            rhs,
        )
        if m_abs:
            bits = int(m_abs.group(1))
            a = self._resolve_c_tok(m_abs.group(2), val_exprs)
            sty = self._bits_to_int_c(bits, signed=True)
            uty = self._bits_to_uint_c(bits)
            return (f"(((({sty})({a}) < ({sty})0) ? (({uty})0 - ({uty})({a})) : ({uty})({a})))", bits)

        # LLVM 2-arg intrinsics: `umax`, `umin`, `smax`, `smin`, `uadd.sat`, `usub.sat`
        m_mm = re.match(
            r"call\s+i(\d+)\s+@llvm\.(umax|umin|smax|smin|uadd\.sat|usub\.sat)\.[a-z0-9.]+\(\s*i\d+\s+([^,]+),\s*i\d+\s+([^)]+)\)",
            rhs,
        )
        if m_mm:
            bits = int(m_mm.group(1))
            op = m_mm.group(2)
            a = self._resolve_c_tok(m_mm.group(3), val_exprs)
            b = self._resolve_c_tok(m_mm.group(4), val_exprs)
            if op in ("umax", "umin", "smax", "smin"):
                ty = self._bits_to_int_c(bits, signed=op.startswith("s"))
                cmp_op = ">" if op.endswith("max") else "<"
                return (f"((({ty})({a}) {cmp_op} ({ty})({b})) ? ({ty})({a}) : ({ty})({b}))", bits)
            uty = self._bits_to_uint_c(bits)
            max_lit = f"0x{((1 << bits) - 1):x}ULL"
            if op == "uadd.sat":
                return (
                    f"(((({uty})({a}) + ({uty})({b})) < ({uty})({a})) ? ({uty}){max_lit} : (({uty})({a}) + ({uty})({b})))",
                    bits,
                )
            return (f"((({uty})({a}) < ({uty})({b})) ? ({uty})0 : (({uty})({a}) - ({uty})({b})))", bits)

        # Funnel shifts `fshl` / `fshr`
        m_fsh = re.match(
            r"call\s+i(\d+)\s+@llvm\.(fshl|fshr)\.[a-z0-9.]+\(\s*i\d+\s+([^,]+),\s*i\d+\s+([^,]+),\s*i\d+\s+([^)]+)\)",
            rhs,
        )
        if m_fsh:
            bits = int(m_fsh.group(1))
            fk = m_fsh.group(2)
            a = self._resolve_c_tok(m_fsh.group(3), val_exprs)
            b = self._resolve_c_tok(m_fsh.group(4), val_exprs)
            c = self._resolve_c_tok(m_fsh.group(5), val_exprs)
            uty = self._bits_to_uint_c(bits)
            wty = "unsigned __int128" if bits == 64 else "uint64_t"
            if fk == "fshl":
                return (
                    f"(({uty})((((({wty})({uty})({a}) << {bits}) | ({wty})({uty})({b})) << (({uty})({c}) % {bits}U)) >> {bits}))",
                    bits,
                )
            return (
                f"(({uty})(((({wty})({uty})({a}) << {bits}) | ({wty})({uty})({b})) >> (({uty})({c}) % {bits}U)))",
                bits,
            )

        m_bswap = re.match(r"call\s+i(\d+)\s+@llvm\.bswap\.[a-z0-9.]+\(\s*i\d+\s+([^)]+)\)", rhs)
        if m_bswap:
            bits = int(m_bswap.group(1))
            a = self._resolve_c_tok(m_bswap.group(2), val_exprs)
            fn = {16: "__builtin_bswap16", 32: "__builtin_bswap32", 64: "__builtin_bswap64"}.get(
                bits, "__builtin_bswap64"
            )
            return (f"{fn}({a})", bits)

        m_bitop = re.match(
            r"call\s+i(\d+)\s+@llvm\.(cttz|ctlz|ctpop)\.[a-z0-9.]+\(\s*i\d+\s+([^,)]+)",
            rhs,
        )
        if m_bitop:
            bits = int(m_bitop.group(1))
            bop = m_bitop.group(2)
            a = self._resolve_c_tok(m_bitop.group(3), val_exprs)
            if bop == "cttz":
                return (f"((uint64_t)({a}) ? (uint64_t)__builtin_ctzll((uint64_t)({a})) : {bits}ULL)", bits)
            if bop == "ctlz":
                off = 64 - bits
                return (f"((uint64_t)({a}) ? (uint64_t)(__builtin_clzll((uint64_t)({a})) - {off}) : {bits}ULL)", bits)
            return (f"((uint64_t)__builtin_popcountll((uint64_t)({a})))", bits)

        # Casts: zext, sext, trunc
        m_cast = re.match(r"(zext|sext|trunc)\s+i(\d+)\s+([^\s]+)\s+to\s+i(\d+)", rhs)
        if m_cast:
            ckind, src_b, src_tok, dst_b = (
                m_cast.group(1),
                int(m_cast.group(2)),
                m_cast.group(3),
                int(m_cast.group(4)),
            )
            sv = self._resolve_c_tok(src_tok, val_exprs)
            if dst_b > 64:
                c_src = "__int128" if ckind == "sext" else "unsigned __int128"
                src_inner = self._bits_to_int_c(src_b, signed=(ckind == "sext"))
                return (f"(({c_src})({src_inner})({sv}))", dst_b)
            if dst_b == 1:
                return (f"(({sv}) & 1U)", 1)
            if ckind == "sext":
                s_src = self._bits_to_int_c(src_b, signed=True)
                s_dst = self._bits_to_int_c(dst_b, signed=True)
                u_dst = self._bits_to_uint_c(dst_b)
                return (f"(({u_dst})({s_dst})({s_src})({sv}))", dst_b)
            u_dst = self._bits_to_uint_c(dst_b)
            u_src = self._bits_to_uint_c(src_b) if src_b > 1 else "uint8_t"
            return (f"(({u_dst})({u_src})({sv}))", dst_b)

        # icmp
        m_cmp = re.match(r"icmp\s+([a-z]+)\s+i(\d+)\s+([^,]+),\s*(.+)$", rhs)
        if m_cmp:
            pred, bits = m_cmp.group(1), int(m_cmp.group(2))
            a = self._resolve_c_tok(m_cmp.group(3), val_exprs)
            b = self._resolve_c_tok(m_cmp.group(4), val_exprs)
            signed = pred.startswith("s")
            ty = self._bits_to_int_c(bits, signed=signed) if bits > 1 else "uint8_t"
            op_str = {
                "eq": "==",
                "ne": "!=",
                "ult": "<",
                "ule": "<=",
                "ugt": ">",
                "uge": ">=",
                "slt": "<",
                "sle": "<=",
                "sgt": ">",
                "sge": ">=",
            }.get(pred, "==")
            return (f"(({ty})({a}) {op_str} ({ty})({b}))", 1)

        # select
        m_sel = re.match(r"select\s+i1\s+([^,]+),\s*i(\d+)\s+([^,]+),\s*i\d+\s+(.+)$", rhs)
        if m_sel:
            c = self._resolve_c_tok(m_sel.group(1), val_exprs)
            bits = int(m_sel.group(2))
            tv = self._resolve_c_tok(m_sel.group(3), val_exprs)
            fv = self._resolve_c_tok(m_sel.group(4), val_exprs)
            return (f"(({c}) ? ({tv}) : ({fv}))", bits)

        # Binary integer arithmetic & bitwise ops
        m_bin = re.match(
            r"(add|sub|mul|udiv|sdiv|urem|srem|and|or|xor|shl|lshr|ashr)\s+i(\d+)\s+([^,]+),\s*(.+)$",
            rhs,
        )
        if m_bin:
            op, bits = m_bin.group(1), int(m_bin.group(2))
            t1_raw, t2_raw = m_bin.group(3).strip(), m_bin.group(4).strip()
            a = self._resolve_c_tok(t1_raw, val_exprs)
            b = self._resolve_c_tok(t2_raw, val_exprs)

            if op in ("add", "sub") and bits == 64:
                n1 = self._norm_tok(t1_raw)
                n2 = self._norm_tok(t2_raw)
                for p_tok, c_str in ((n1, t2_raw), (n2, t1_raw if op == "add" else "")):
                    if p_tok in ptr_struct_types and c_str:
                        try:
                            disp = int(c_str, 0)
                            if op == "sub":
                                disp = -disp
                            sname, pexpr = ptr_struct_types[p_tok]
                            self._record_offset_ptr(lhs, sname, pexpr, disp, ptr_struct_types)
                        except ValueError:
                            pass

            if bits == 1:
                bop = {"and": "&&", "or": "||", "xor": "!="}.get(op, "^")
                return (f"(({a}) {bop} ({b}))", 1)

            signed = op in ("sdiv", "srem", "ashr")
            ty = self._bits_to_int_c(bits, signed=signed)
            c_op = {
                "add": "+",
                "sub": "-",
                "mul": "*",
                "udiv": "/",
                "sdiv": "/",
                "urem": "%",
                "srem": "%",
                "and": "&",
                "or": "|",
                "xor": "^",
                "shl": "<<",
                "lshr": ">>",
                "ashr": ">>",
            }[op]
            return (f"(({ty})({a}) {c_op} ({ty})({b}))", bits)

        return (None, 64)

    def _record_offset_ptr(
        self,
        lhs: str,
        sname: str,
        pexpr: str,
        disp: int,
        ptr_struct_types: dict[str, tuple[str, str]],
    ) -> None:
        if disp < 0:
            # Check `_OBJECT_HEADER.Body` (+0x30) CONTAINING_RECORD on Executive objects!
            obj_hdr = self.structs.get("_OBJECT_HEADER")
            if obj_hdr is not None:
                body_fld = next((f for f in obj_hdr.fields if f.name == "Body"), None)
                body_off = body_fld.offset if body_fld is not None else 0x30
                hdr_off = body_off + disp
                if 0 <= hdr_off < body_off and obj_hdr.field_at_offset(hdr_off) is not None:
                    cr_expr = f"CONTAINING_RECORD({pexpr}, struct _OBJECT_HEADER, Body)"
                    if hdr_off == 0:
                        ptr_struct_types[lhs] = ("_OBJECT_HEADER", cr_expr)
                    else:
                        ptr_struct_types[lhs] = (
                            "_OBJECT_HEADER",
                            f"__FIELD_ADDR__:_OBJECT_HEADER:{cr_expr}:{hdr_off}",
                        )
                    return

            pos_off = -disp
            for cand_st in self.structs.values():
                for fld in cand_st.fields:
                    if fld.offset == pos_off and (
                        "LIST_ENTRY" in fld.c_type or fld.name.endswith("Links")
                    ):
                        cr_expr = (
                            f"CONTAINING_RECORD({pexpr}, struct {cand_st.name}, {fld.name})"
                        )
                        ptr_struct_types[lhs] = (cand_st.name, cr_expr)
                        return
        elif sname != "__VOID_OB_BODY__":
            ptr_struct_types[lhs] = (sname, f"__FIELD_ADDR__:{sname}:{pexpr}:{disp}")

    def _format_mem_lvalue(
        self,
        ptr_tok: str,
        bits: int,
        val_exprs: dict[str, str],
        ptr_struct_types: dict[str, tuple[str, str]],
    ) -> tuple[str, str]:
        fallback_ty = self._bits_to_uint_c(bits)
        if ptr_tok in ptr_struct_types:
            sname, pexpr = ptr_struct_types[ptr_tok]
            disp = 0
            base_c = pexpr
            if pexpr.startswith("__FIELD_ADDR__:"):
                _, sname, base_c, disp_s = pexpr.split(":", 3)
                disp = int(disp_s)
            sdef = self.structs.get(sname)
            if sdef:
                resolved = sdef.resolve_nested_field_path(
                    offset=disp,
                    access_size=max(bits // 8, 1),
                    all_structs=self.structs,
                    is_address_only=False,
                )
                if resolved is not None:
                    path_str, leaf_fld = resolved
                    if self._is_emittable_field_path(sname, path_str):
                        wrapped = f"({base_c})" if (" " in base_c or base_c.startswith("CONTAINING_RECORD")) else base_c
                        return (f"{wrapped}->{path_str}", leaf_fld.c_type)
            off_part = f" + 0x{disp:x}" if disp >= 0 else f" - 0x{-disp:x}"
            if disp == 0:
                off_part = ""
            return (
                f"(*({fallback_ty}*)((uint8_t*)(uintptr_t)({base_c}){off_part}))",
                fallback_ty,
            )

        addr_c = self._resolve_c_tok(ptr_tok, val_exprs)
        return (f"(*({fallback_ty}*)(uintptr_t)({addr_c}))", fallback_ty)

    @classmethod
    def _emitted_field_map(cls, st: StructDef) -> dict[str, StructField]:
        used_names: set[str] = set()
        if st.is_union:
            out: dict[str, StructField] = {}
            for fld in st.fields:
                if fld.bit_size is not None:
                    continue
                fname = cls._unique_field_name(fld.name, used_names)
                out[fname] = fld
            return out

        non_bf = [
            f
            for f in sorted(st.fields, key=lambda x: (x.offset, -x.size, x.name))
            if f.bit_size is None and f.offset < max(st.size, 1)
        ]
        renamed: list[tuple[StructField, str]] = []
        for fld in non_bf:
            fname = cls._unique_field_name(fld.name, used_names)
            renamed.append((fld, fname))

        lane_ends: list[int] = []
        out = {}
        for fld, fname in renamed:
            f_end = fld.offset + max(fld.size, 1)
            if st.size > 0 and f_end > st.size:
                continue
            placed = False
            for l_idx, cur_end in enumerate(lane_ends):
                if fld.offset >= cur_end:
                    lane_ends[l_idx] = f_end
                    out[fname] = fld
                    placed = True
                    break
            if not placed and len(lane_ends) < 12:
                lane_ends.append(f_end)
                out[fname] = fld
        return out

    def _is_emittable_field_path(self, sname: str, path_str: str) -> bool:
        parts = path_str.split(".")
        cur_sname = sname
        for idx, part in enumerate(parts):
            st = self.structs.get(cur_sname)
            if st is None:
                return False
            fmap = self._emitted_field_map(st)
            fld = fmap.get(part)
            if fld is None:
                return False
            if idx + 1 < len(parts):
                if fld.is_pointer:
                    return False
                m = re.match(r"^(struct|union)\s+([A-Za-z0-9_]+)$", fld.c_type.strip())
                if not m:
                    return False
                sub_name = m.group(2)
                sub_st = self.structs.get(sub_name)
                if sub_st is None or not (
                    sub_st.size <= 2048 or sub_name in ("_KTHREAD", "_OBJECT_HEADER")
                ):
                    return False
                cur_sname = sub_name
        return True

    def _emit_terminator(
        self,
        blk: IRBasicBlock,
        next_lbl: str | None,
        signature: InferredFuncSignature,
        val_exprs: dict[str, str],
        phi_edge_copies: dict[tuple[str, str], list[str]],
        resolve_placeholders,
    ) -> list[str]:
        term = blk.terminator
        if term.startswith("ret "):
            if signature.is_void_return or term == "ret void":
                return ["return;"]
            m_ret = re.match(r"ret\s+i\d+\s+(.+)$", term)
            if m_ret:
                rv = self._resolve_c_tok(m_ret.group(1).strip(), val_exprs)
                return [f"return {self._cast_return_expr(rv, signature.return_type)};"]
            return ["return 0;"]

        if term.startswith("br label %"):
            tgt = term.split("%", 1)[1].strip().strip('"')
            lines = [
                resolve_placeholders(cp)
                for cp in phi_edge_copies.get((blk.label, tgt), [])
            ]
            if tgt != next_lbl:
                lines.append(f"goto {self._c_label(tgt)};")
            return lines

        m_cbr = re.match(
            r"br\s+i1\s+([^,]+),\s*label\s+%([^\s,]+),\s*label\s+%([^\s,]+)",
            term,
        )
        if m_cbr:
            cond = self._resolve_c_tok(m_cbr.group(1).strip(), val_exprs)
            t_lbl = m_cbr.group(2).strip('"')
            f_lbl = m_cbr.group(3).strip('"')
            out: list[str] = [f"if ({cond}) {{"]
            for cp in phi_edge_copies.get((blk.label, t_lbl), []):
                out.append(f"    {resolve_placeholders(cp)}")
            out.append(f"    goto {self._c_label(t_lbl)};")
            out.append("}")
            for cp in phi_edge_copies.get((blk.label, f_lbl), []):
                out.append(resolve_placeholders(cp))
            if f_lbl != next_lbl:
                out.append(f"goto {self._c_label(f_lbl)};")
            return out

        if term.startswith("switch "):
            m_sw = re.match(
                r"switch\s+i(\d+)\s+([^,]+),\s*label\s+%([^\s\[]+)\s*\[(.*)\]",
                term,
            )
            if m_sw:
                disc = self._resolve_c_tok(m_sw.group(2).strip(), val_exprs)
                def_lbl = m_sw.group(3).strip('"')
                cases = re.findall(r"i\d+\s+(-?\d+),\s*label\s+%([^\s\]]+)", m_sw.group(4))
                out = [f"switch ({disc}) {{"]
                for val_s, tgt_raw in cases:
                    tl = tgt_raw.strip('"')
                    out.append(f"    case {val_s}LL:")
                    for cp in phi_edge_copies.get((blk.label, tl), []):
                        out.append(f"        {resolve_placeholders(cp)}")
                    out.append(f"        goto {self._c_label(tl)};")
                out.append("    default:")
                for cp in phi_edge_copies.get((blk.label, def_lbl), []):
                    out.append(f"        {resolve_placeholders(cp)}")
                out.append(f"        goto {self._c_label(def_lbl)};")
                out.append("}")
                return out

        if term == "unreachable":
            return ["return;"] if signature.is_void_return else ["return 0;"]

        return []

    # ------------------------------------------------------------------
    # Low-Level LLVM Textual Parser & Type Formatting Helpers
    # ------------------------------------------------------------------
    def _parse_ir_blocks(
        self, llvm_ir: str
    ) -> tuple[list[IRBasicBlock], list[str]]:
        raw_blocks: list[tuple[str, list[str]]] = []
        arg_names: list[str] = []
        in_fn = False
        cur_label = "entry"
        cur_lines: list[str] = []
        all_lines = llvm_ir.splitlines()
        idx = 0

        while idx < len(all_lines):
            line = all_lines[idx].split(";", 1)[0].strip()
            idx += 1
            if not line:
                continue
            if not in_fn:
                if line.startswith("define "):
                    in_fn = True
                    m_args = re.search(r"@[^\s(]+\(([^)]*)\)", line)
                    if m_args and m_args.group(1).strip():
                        for part in m_args.group(1).split(","):
                            m_p = re.search(r"%([A-Za-z0-9_.\"]+)", part)
                            if m_p:
                                arg_names.append("%" + m_p.group(1).strip('"'))
                continue

            if line == "}":
                if cur_lines:
                    raw_blocks.append((cur_label, cur_lines))
                break
            if line == "{":
                continue

            if line.startswith("switch ") and "]" not in line:
                parts = [line]
                while idx < len(all_lines):
                    nxt = all_lines[idx].split(";", 1)[0].strip()
                    idx += 1
                    parts.append(nxt)
                    if "]" in nxt:
                        break
                line = " ".join(parts)

            if line.endswith(":") and "=" not in line:
                if cur_lines:
                    raw_blocks.append((cur_label, cur_lines))
                cur_label = line[:-1].strip().strip('"')
                cur_lines = []
            else:
                cur_lines.append(line)

        parsed: list[IRBasicBlock] = []
        for lbl, stmts in raw_blocks:
            phis: list[tuple[str, int, list[tuple[str, str]]]] = []
            body: list[str] = []
            term = "ret void"
            for i, s in enumerate(stmts):
                m_phi = re.match(
                    r"(%[A-Za-z0-9_.\"]+)\s*=\s*phi\s+(?:[a-z]+\s+)*i(\d+)\s+(.+)$", s
                )
                if m_phi:
                    lhs = self._norm_tok(m_phi.group(1))
                    bits = int(m_phi.group(2))
                    pairs = [
                        (v.strip(), b.strip().strip('"'))
                        for v, b in re.findall(r"\[\s*([^,]+),\s*%([^\s\]]+)\s*\]", m_phi.group(3))
                    ]
                    phis.append((lhs, bits, pairs))
                elif i == len(stmts) - 1 and s.startswith(("ret ", "br ", "switch ")):
                    term = s
                else:
                    body.append(s)
            parsed.append(IRBasicBlock(label=lbl, phis=phis, stmts=body, terminator=term))
        return parsed, arg_names

    def _count_ssa_uses(self, ir_blocks: list[IRBasicBlock]) -> dict[str, int]:
        counts: dict[str, int] = {}
        pat = re.compile(r'%("?[A-Za-z0-9_.]+"?)')
        for blk in ir_blocks:
            for _lhs, _bits, pairs in blk.phis:
                for val_tok, _ in pairs:
                    for m in pat.finditer(val_tok):
                        k = "%" + m.group(1).strip('"')
                        counts[k] = counts.get(k, 0) + 1
            for s in blk.stmts:
                rhs = s.split("=", 1)[1] if "=" in s else s
                for m in pat.finditer(rhs):
                    k = "%" + m.group(1).strip('"')
                    counts[k] = counts.get(k, 0) + 1
            for m in pat.finditer(blk.terminator):
                k = "%" + m.group(1).strip('"')
                counts[k] = counts.get(k, 0) + 1
        return counts

    @staticmethod
    def _collect_branch_targets(ir_blocks: list[IRBasicBlock]) -> set[str]:
        targets: set[str] = set()
        for blk in ir_blocks:
            for m in re.finditer(r'label\s+%("?[A-Za-z0-9_.]+"?)', blk.terminator):
                targets.add(m.group(1).strip('"'))
        return targets

    @staticmethod
    def _norm_tok(tok: str) -> str:
        t = tok.strip()
        if t.startswith("%"):
            return "%" + t[1:].strip('"')
        return t

    @staticmethod
    def _tok_Placeholder(tok: str) -> str:
        return f"__SSA_TOK({tok.strip()})__"

    def _resolve_c_tok(self, tok: str, val_exprs: dict[str, str]) -> str:
        norm = self._norm_tok(tok)
        if norm in val_exprs:
            return val_exprs[norm]
        if norm in ("true",):
            return "1U"
        if norm in ("false", "null", "undef", "poison", "zeroinitializer"):
            return "0ULL"
        m_itp = re.match(r"inttoptr\s*\(\s*i\d+\s+(-?\d+)\s+to\s+(?:ptr|i\d+\*)\s*\)", norm)
        if m_itp:
            u64 = int(m_itp.group(1)) & 0xFFFFFFFFFFFFFFFF
            return f"0x{u64:x}ULL"
        try:
            ival = int(norm, 0)
            if ival < 0:
                u64 = ival & 0xFFFFFFFFFFFFFFFF
                return f"0x{u64:x}ULL"
            return f"0x{ival:x}ULL" if ival >= 16 else f"{ival}ULL"
        except ValueError:
            return self._sanitize_ident(norm)

    def _pointee_struct_name(self, c_type: str) -> str | None:
        clean = c_type.strip()
        for prefix in ("struct ", "union ", "const struct ", "const union "):
            if clean.startswith(prefix) and clean.endswith("*"):
                cand = clean[len(prefix) : -1].strip()
                if "*" not in cand:
                    return cand
        for sname, sdef in self.structs.items():
            if sdef.pointer_typedef and clean == sdef.pointer_typedef:
                return sname
        return None

    @staticmethod
    def _sanitize_ident(ssa_name: str) -> str:
        raw = ssa_name.lstrip("%").strip('"')
        cleaned = re.sub(r"[^A-Za-z0-9_]", "_", raw)
        if not cleaned or cleaned[0].isdigit():
            cleaned = f"v_{cleaned}"
        return f"ssa_{cleaned}"

    @staticmethod
    def _c_label(lbl: str) -> str:
        cleaned = re.sub(r"[^A-Za-z0-9_]", "_", lbl.strip('"'))
        return f"L_{cleaned}"

    @staticmethod
    def _bits_to_uint_c(bits: int) -> str:
        if bits <= 8:
            return "uint8_t"
        if bits <= 16:
            return "uint16_t"
        if bits <= 32:
            return "uint32_t"
        if bits <= 64:
            return "uint64_t"
        return "unsigned __int128"

    @staticmethod
    def _bits_to_int_c(bits: int, signed: bool = False) -> str:
        if not signed:
            return VerifiedCEmitter._bits_to_uint_c(bits)
        if bits <= 8:
            return "int8_t"
        if bits <= 16:
            return "int16_t"
        if bits <= 32:
            return "int32_t"
        if bits <= 64:
            return "int64_t"
        return "__int128"
